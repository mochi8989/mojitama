const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const dir=path.join(__dirname,'..'),R=require('../roman.js'),words=require('../data/words.json');
const ids=new Set(),readings=new Set(),displays=new Set();
for(const w of words){
  assert.match(w.id,/^[a-z][a-z0-9_-]*$/);assert(!ids.has(w.id),w.id);ids.add(w.id);
  for(const [set,value] of [[readings,w.reading],[displays,w.display.normalize('NFKC').trim()]]){
    assert(value && !set.has(value),w.id+': '+value);set.add(value);
  }
  assert(typeof w.category==='string' && w.category.trim() && ['normal','fun'].includes(w.kind));
  assert(Number.isInteger(w.difficulty)&&w.difficulty>=1&&w.difficulty<=5);
  assert(!w.rare || w.kind==='fun');
  assert.equal(R.standard(w.reading),w.romaji,w.id);assert.equal(w.length,w.romaji.length);
  assert.match(w.romaji,/^[A-Z-]+$/);assert.equal(R.guide(R.segments(w.reading),w.romaji),'');
}
const normal=words.filter(w=>w.kind==='normal'),vocab=normal.filter(w=>!['かな','ぶん'].includes(w.category));
assert(vocab.length>=500 && words.length>=600);
for(let level=1;level<=5;level++)assert(normal.some(w=>w.difficulty===level));
const fallback='// Generated by tools/validate.cjs --build for file:// play.\nwindow.offlineWords='+JSON.stringify(words)+';\n';
const dest=path.join(dir,'data/offline.js');
if(process.argv.includes('--build'))fs.writeFileSync(dest,fallback);else assert.equal(fs.readFileSync(dest,'utf8'),fallback,'Rebuild offline.js');
console.log({normal:normal.length,vocabulary:vocab.length,fun:words.length-normal.length,total:words.length});
